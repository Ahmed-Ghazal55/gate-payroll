export function t(key: string, lang: Language = currentLanguage): string {
  return DICT[lang]?.[key] ?? DICT.ar[key] ?? key;
}

export function pickLang(obj: any, baseKey: string, lang: Language = currentLanguage): string {
  if (!obj) return '';
  const suffix = lang === 'en' ? 'En' : lang === 'ur' ? 'Ur' : 'Ar';
  return String(obj[baseKey + suffix] || obj[baseKey + 'Ar'] || obj[baseKey] || '');
}

