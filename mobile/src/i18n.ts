export type Language = 'ar' | 'en' | 'ur';

const LANG_KEY = 'gate_rider_lang';
let currentLanguage: Language = 'ar';

try {
  const saved = localStorage.getItem(LANG_KEY) || localStorage.getItem('gate-language');
  if (saved === 'ar' || saved === 'en' || saved === 'ur') {
    currentLanguage = saved;
  }
} catch {}

export function getLanguage(): Language {
  return currentLanguage;
}

export function applyDirection(lang: Language = currentLanguage): void {
  if (typeof document === 'undefined') return;
  document.documentElement.lang = lang;
  const dir = lang === 'en' ? 'ltr' : 'rtl';
  document.documentElement.dir = dir;
  if (document.body) {
    document.body.dir = dir;
  }
}

export function setLanguage(lang: Language): void {
  if (lang !== 'ar' && lang !== 'en' && lang !== 'ur') lang = 'ar';
  currentLanguage = lang;
  try {
    localStorage.setItem(LANG_KEY, lang);
    localStorage.setItem('gate-language', lang);
  } catch {}
  applyDirection(lang);
}

