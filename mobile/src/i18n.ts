export const RETIRED_BANKS = ['40', '50'];

export function normalizeIbanBody(raw: string): string {
  let s = String(raw || '')
    .replace(/[٠-٩]/g, d => String(d.charCodeAt(0) - 0x0660))
    .replace(/[۰-۹]/g, d => String(d.charCodeAt(0) - 0x06f0))
    .toUpperCase()
    .replace(/[^0-9A-Z]/g, '');
  if (s.startsWith('IBAN')) s = s.slice(4);
  if (s.startsWith('SA')) s = s.slice(2);
  return s;
}

export function isIbanMod97Valid(body: string): boolean {
  if (!/^[0-9]{22}$/.test(body)) return false;
  let r = 0;
  for (const c of body.slice(2) + '2810' + body.slice(0, 2)) {
    r = (r * 10 + Number(c)) % 97;
  }
  return r === 1;
}

export function validateSaudiIban(raw: string): {
  valid: boolean;
  fullIban: string;
  bankCode: string;
  bank?: { code: string; ar: string; en: string; swift: string };
  errorKey?: string;
} {
  const body = normalizeIbanBody(raw);
  if (!isIbanMod97Valid(body)) {
    return { valid: false, fullIban: 'SA' + body, bankCode: '', errorKey: 'invalidIban' };
  }
  const code = body.slice(2, 4);
  if (RETIRED_BANKS.includes(code)) {
    return { valid: false, fullIban: 'SA' + body, bankCode: code, errorKey: 'bankRetired' };
  }
  const bank = SALARY_BANKS.find(b => b.code === code);
  if (!bank) {
    return { valid: false, fullIban: 'SA' + body, bankCode: code, errorKey: 'bankNotAccepted' };
  }
  return { valid: true, fullIban: 'SA' + body, bankCode: code, bank };
}
